-- Tienda de Zapatos - esquema PostgreSQL para Neon
-- Basado en database/tienda_zapatos.sql del repositorio Tienda-Zapatos.
-- Ejecutar en el SQL Editor de la base de datos Neon destino.
-- Este script crea la estructura; no migra registros de otra base MySQL.
-- La aplicación crea datos demo al iniciar si tienda.datos-demo=true.
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.usuarios (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(100) NOT NULL,
    correo   VARCHAR(150) NOT NULL,
    password VARCHAR(255) NOT NULL,
    telefono VARCHAR(20),
    rol      VARCHAR(20) NOT NULL,
    activo   BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuarios_correo UNIQUE (correo),
    CONSTRAINT ck_usuarios_rol CHECK (
        rol IN ('ADMINISTRADOR', 'GERENTE', 'VENDEDOR', 'ALMACENISTA', 'CLIENTE')
    )
);

CREATE TABLE IF NOT EXISTS public.zapatos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia  VARCHAR(20) NOT NULL,
    nombre      VARCHAR(120) NOT NULL,
    marca       VARCHAR(60) NOT NULL,
    categoria   VARCHAR(60) NOT NULL,
    color       VARCHAR(40) NOT NULL,
    precio      DECIMAL(12,2) NOT NULL,
    descripcion VARCHAR(500),
    imagen      VARCHAR(300),
    activo      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_zapatos_referencia UNIQUE (referencia)
);

CREATE TABLE IF NOT EXISTS public.tallas_stock (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zapato_id BIGINT NOT NULL,
    talla     INTEGER NOT NULL,
    stock     INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_zapato_talla UNIQUE (zapato_id, talla),
    CONSTRAINT fk_tallas_zapato FOREIGN KEY (zapato_id)
        REFERENCES public.zapatos (id),
    CONSTRAINT ck_talla_rango CHECK (talla BETWEEN 34 AND 45),
    CONSTRAINT ck_stock_no_negativo CHECK (stock >= 0)
);

CREATE TABLE IF NOT EXISTS public.pedidos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero      VARCHAR(30) NOT NULL,
    canal       VARCHAR(15) NOT NULL,
    estado      VARCHAR(15) NOT NULL,
    fecha       TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    direccion   VARCHAR(250),
    metodo_pago VARCHAR(20) NOT NULL,
    cliente_id  BIGINT,
    vendedor_id BIGINT,
    subtotal    DECIMAL(14,2) NOT NULL DEFAULT 0,
    iva         DECIMAL(14,2) NOT NULL DEFAULT 0,
    total       DECIMAL(14,2) NOT NULL DEFAULT 0,
    CONSTRAINT uk_pedidos_numero UNIQUE (numero),
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id)
        REFERENCES public.usuarios (id),
    CONSTRAINT fk_pedidos_vendedor FOREIGN KEY (vendedor_id)
        REFERENCES public.usuarios (id),
    CONSTRAINT ck_pedidos_canal CHECK (canal IN ('WEB', 'PRESENCIAL')),
    CONSTRAINT ck_pedidos_estado CHECK (
        estado IN ('PENDIENTE', 'CONFIRMADO', 'ENVIADO', 'ENTREGADO', 'CANCELADO')
    ),
    CONSTRAINT ck_pedidos_pago CHECK (
        metodo_pago IN ('CONTRA_ENTREGA', 'TRANSFERENCIA', 'EFECTIVO', 'TARJETA')
    )
);

CREATE TABLE IF NOT EXISTS public.detalles_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT NOT NULL,
    zapato_id       BIGINT NOT NULL,
    talla_stock_id  BIGINT NOT NULL,
    nombre_zapato   VARCHAR(120) NOT NULL,
    talla           INTEGER NOT NULL,
    cantidad        INTEGER NOT NULL,
    precio_unitario DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_det_pedido FOREIGN KEY (pedido_id)
        REFERENCES public.pedidos (id),
    CONSTRAINT fk_det_zapato FOREIGN KEY (zapato_id)
        REFERENCES public.zapatos (id),
    CONSTRAINT fk_det_talla FOREIGN KEY (talla_stock_id)
        REFERENCES public.tallas_stock (id),
    CONSTRAINT ck_det_cantidad CHECK (cantidad > 0)
);

CREATE TABLE IF NOT EXISTS public.movimientos_inventario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    talla_stock_id BIGINT NOT NULL,
    tipo           VARCHAR(20) NOT NULL,
    cantidad       INTEGER NOT NULL,
    fecha          TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    usuario_id     BIGINT NOT NULL,
    referencia     VARCHAR(30),
    CONSTRAINT fk_mov_talla FOREIGN KEY (talla_stock_id)
        REFERENCES public.tallas_stock (id),
    CONSTRAINT fk_mov_usuario FOREIGN KEY (usuario_id)
        REFERENCES public.usuarios (id),
    CONSTRAINT ck_mov_tipo CHECK (tipo IN ('ENTRADA', 'AJUSTE', 'VENTA', 'DEVOLUCION'))
);

-- Índices para claves foráneas y consultas frecuentes.
CREATE INDEX IF NOT EXISTS ix_pedidos_fecha ON public.pedidos (fecha);
CREATE INDEX IF NOT EXISTS ix_pedidos_cliente_id ON public.pedidos (cliente_id);
CREATE INDEX IF NOT EXISTS ix_pedidos_vendedor_id ON public.pedidos (vendedor_id);
CREATE INDEX IF NOT EXISTS ix_tallas_stock_zapato_id ON public.tallas_stock (zapato_id);
CREATE INDEX IF NOT EXISTS ix_detalles_pedido_pedido_id ON public.detalles_pedido (pedido_id);
CREATE INDEX IF NOT EXISTS ix_detalles_pedido_zapato_id ON public.detalles_pedido (zapato_id);
CREATE INDEX IF NOT EXISTS ix_detalles_pedido_talla_stock_id ON public.detalles_pedido (talla_stock_id);
CREATE INDEX IF NOT EXISTS ix_movimientos_talla_stock_id ON public.movimientos_inventario (talla_stock_id);
CREATE INDEX IF NOT EXISTS ix_movimientos_usuario_id ON public.movimientos_inventario (usuario_id);

COMMIT;

